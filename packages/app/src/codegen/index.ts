import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, relative, resolve, sep } from 'node:path'

export interface GeneratePagesOptions {
  readonly pagesDir: string
  readonly primaryPages?: ReadonlyArray<string>
}

interface PageFile {
  readonly key: string
  readonly path: string
}

const pageKeyPattern = /^[a-z][A-Za-z0-9]*$/
const reservedTags = new Set([
  'EnteredRoute', 'LoadedPageModule', 'FailedPageModule', 'ClickedRetryPage', 'ClickedReloadPage',
  'RequestedPrefetch', 'CompletedPrefetch', 'GotPwaEvent', 'NewVersionAvailable', 'ClickedApplyUpdate',
  'CompletedApplyUpdate', 'FailedApplyUpdate',
])

function listPages(appRoot: string, pagesDir: string): ReadonlyArray<PageFile> {
  const absolutePagesDir = resolve(appRoot, pagesDir)
  const pages = readdirSync(absolutePagesDir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith('.ts') && !entry.name.endsWith('.test.ts') && !entry.name.endsWith('.spec.ts'))
    .map((entry) => ({
      key: basename(entry.name, '.ts'),
      path: `./${relative(dirname(resolve(appRoot, 'src/pages.gen.ts')), join(absolutePagesDir, basename(entry.name, '.ts'))).split(sep).join('/')}`,
    }))
    .sort((left, right) => left.key < right.key ? -1 : left.key > right.key ? 1 : 0)

  for (const { key } of pages) {
    if (!pageKeyPattern.test(key)) throw new Error(`page key "${key}" must match ^[a-z][A-Za-z0-9]*$`)
  }
  let packageJson: string | undefined
  try {
    packageJson = readFileSync(join(absolutePagesDir, 'package.json'), 'utf8')
  } catch {
    packageJson = undefined
  }
  if (packageJson === undefined || JSON.parse(packageJson).sideEffects !== false) {
    throw new Error('pages package.json must declare "sideEffects": false')
  }
  if (pages.length === 0) throw new Error('no page modules found')
  return pages
}

function pageTag(key: string): string {
  return `Got${key[0]!.toUpperCase()}${key.slice(1)}PageMessage`
}

export function generatePages(appRoot: string, options: GeneratePagesOptions): { path: string; source: string } {
  const pages = listPages(appRoot, options.pagesDir)
  for (const key of options.primaryPages ?? []) {
    if (!pages.some((page) => page.key === key)) throw new Error(`primaryPages names unknown page "${key}"`)
  }
  const tags = pages.map(({ key }) => pageTag(key))
  if (new Set(tags).size !== tags.length || tags.some((tag) => reservedTags.has(tag))) {
    throw new Error('rejects page key whose tag collides with a reserved kit tag')
  }

  const pageTypes = ''
  const pageTypeMap = pages.map(({ key, path }) => `  readonly ${key}: typeof import('${path}').page`).join('\n')
  const loaders = pages.map(({ key, path }) => `  ${key}: () => import('${path}').then(module => module.page),`).join('\n')
  const pageSchema = `[${pages.map(({ key }) => `'${key}'`).join(', ')}]`
  const tagMap = pages.map(({ key }) => `  ${key}: '${pageTag(key)}',`).join('\n')
  const source = `// Generated by @wsagency/wseffect-app/vite from src/pages; do not edit.\nimport { Schema } from 'effect'\nimport { defineTaggedUnion } from 'foldkit/schema'\nimport { bindKit, kitMessageFields, makePages, messageSchema } from '@wsagency/wseffect-app'\n${pageTypes}\n\nexport type Pages = {\n${pageTypeMap}\n}\n\nexport const pages = makePages<Pages>({\n${loaders}\n})\nexport const PageKey = Schema.Literals(${pageSchema})\nexport const KitMessage = defineTaggedUnion({\n  ...kitMessageFields(pages),\n${pages.map(({ key }) => `  ${pageTag(key)}: { message: messageSchema(pages, '${key}') },`).join('\n')}\n})\nexport type KitMessage = typeof KitMessage.Type\nexport const pageMessageTags = {\n${tagMap}\n} as const\nexport const kit = bindKit({ pages, KitMessage, pageMessageTags })\n`
  return { path: resolve(appRoot, 'src/pages.gen.ts'), source }
}

export function checkPages(appRoot: string, options: GeneratePagesOptions): { ok: true } | { ok: false; diff: string } {
  const generated = generatePages(appRoot, options)
  let existing: string
  try {
    existing = readFileSync(generated.path, 'utf8')
  } catch {
    existing = ''
  }
  if (existing === generated.source) return { ok: true }
  const expectedLines = generated.source.split('\n')
  const actualLines = existing.split('\n')
  const differences = [`--- ${generated.path}`, '+++ generated']
  const length = Math.max(expectedLines.length, actualLines.length)
  for (let index = 0; index < length; index += 1) {
    const actual = actualLines[index]
    const expected = expectedLines[index]
    if (actual === expected) continue
    if (actual !== undefined) differences.push(`-${actual}`)
    if (expected !== undefined) differences.push(`+${expected}`)
  }
  return { ok: false, diff: differences.join('\n') }
}

export function writePages(appRoot: string, options: GeneratePagesOptions): string {
  const generated = generatePages(appRoot, options)
  let existing: string | undefined
  try {
    existing = readFileSync(generated.path, 'utf8')
  } catch {
    existing = undefined
  }
  if (existing !== generated.source) writeFileSync(generated.path, generated.source)
  return generated.path
}


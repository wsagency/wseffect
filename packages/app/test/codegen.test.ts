import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, describe, expect, it } from 'vitest'
import { checkPages, generatePages } from '../src/codegen/index.js'

const roots: Array<string> = []

async function fixture(): Promise<string> {
  const root = await mkdtemp(join(tmpdir(), 'wseffect-pages-'))
  roots.push(root)
  await mkdir(join(root, 'src/pages'), { recursive: true })
  await writeFile(join(root, 'src/pages/package.json'), JSON.stringify({ sideEffects: false }))
  await writeFile(join(root, 'src/pages/alpha.ts'), 'export const page = {}\n')
  await writeFile(join(root, 'src/pages/beta.ts'), 'export const page = {}\n')
  await writeFile(join(root, 'src/pages/ignored.test.ts'), 'export const page = {}\n')
  return root
}

afterEach(async () => {
  await Promise.all(roots.splice(0).map((root) => rm(root, { recursive: true, force: true })))
})

describe('page code generation', () => {
  it('generates lazy loaders, page types, schemas, and excludes tests', async () => {
    const root = await fixture()
    const { source } = await generatePages(root, { pagesDir: 'src/pages' })
    expect(source.startsWith('// Generated by @wsagency/wseffect-app/vite from src/pages; do not edit.')).toBe(true)
    expect(source).toContain("from '@wsagency/wseffect-app/runtime'")
    expect(source).toContain("readonly alpha: typeof import('./pages/alpha').page")
    expect(source).toContain("alpha: () => import('./pages/alpha').then(module => module.page)")
    expect(source).toContain("GotAlphaPageMessage: { message: messageSchema(pages, 'alpha') }")
    expect(source).toContain("PageKey = Schema.Literals(['alpha', 'beta'])")
    expect(source).not.toContain('ignored')
  })

  it('rejects invalid page names, missing sideEffects false, and unknown primary pages', async () => {
    const root = await fixture()
    await writeFile(join(root, 'src/pages/Bad-name.ts'), 'export const page = {}\n')
    expect(() => generatePages(root, { pagesDir: 'src/pages' })).toThrow('page key "Bad-name" must match ^[a-z][A-Za-z0-9]*$')
    await rm(join(root, 'src/pages/Bad-name.ts'))
    await writeFile(join(root, 'src/pages/package.json'), JSON.stringify({ sideEffects: true }))
    expect(() => generatePages(root, { pagesDir: 'src/pages' })).toThrow('"sideEffects": false')
    await writeFile(join(root, 'src/pages/package.json'), JSON.stringify({ sideEffects: false }))
    expect(() => generatePages(root, { pagesDir: 'src/pages', primaryPages: ['gamma'] })).toThrow('primaryPages names unknown page "gamma"')
  })

  it('detects generated file drift', async () => {
    const root = await fixture()
    const options = { pagesDir: 'src/pages' }
    const generated = await generatePages(root, options)
    await writeFile(generated.path, generated.source)
    expect(await checkPages(root, options)).toEqual({ ok: true })
    await writeFile(generated.path, `${generated.source}x`)
    const result = await checkPages(root, options)
    expect(result.ok).toBe(false)
    if (!result.ok) expect(result.diff).toContain('-x')
    await expect(readFile(generated.path, 'utf8')).resolves.toBe(`${generated.source}x`)
  })
})
